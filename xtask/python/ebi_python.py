#!/usr/bin/env python3
"""The Python stages of `cargo xtask`: the environment, the Python tests and
the wheel. Standard library only, so it runs on a bare interpreter.

    python xtask/python/ebi_python.py env lock       resolve the dependencies
        declared in pyproject.toml and rewrite requirements.txt (here)
    python xtask/python/ebi_python.py env rebuild    recreate the ebi-pm
        environment from requirements.txt
    python xtask/python/ebi_python.py test           maturin develop into the
        environment, then the Python tests
    python xtask/python/ebi_python.py wheel          build a wheel, install it
        into a fresh environment and run the Python tests against it
    python xtask/python/ebi_python.py wheel-release  the same with a release
        build, leaving the tested wheel in var/wheel-releases

Use it through `cargo xtask python ...` or `cargo xtask test`. The environment
is always recreated from scratch, never edited by hand. `env` needs the base
interpreter, not the environment's own.
"""
import argparse
import os
import re
import shutil
import subprocess
import sys
import time
import tomllib
import venv
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
VENV = ROOT / "ebi-pm"
VAR = ROOT / "var"
REQUIREMENTS = HERE / "requirements.txt"
HEADER = (
    "# Autogenerated by `cargo xtask python env lock`; do not edit. "
    "Source of truth: pyproject.toml\n"
)
PYTHON_TESTS = ["python", "-m", "unittest", "discover", "-s", "tests/python"]


def python_in(environment_directory: Path) -> Path:
    if sys.platform == "win32":
        return environment_directory / "Scripts" / "python.exe"
    return environment_directory / "bin" / "python"


def create_environment() -> Path:
    if Path(sys.prefix).resolve() == VENV.resolve():
        sys.exit(
            "Run this with the base interpreter, not the ebi-pm environment "
            "it would delete."
        )
    venv.EnvBuilder(clear=True, with_pip=True).create(VENV)
    return python_in(VENV)


def pip(
    python: Path, *args: str, capture: bool = False
) -> subprocess.CompletedProcess:
    return subprocess.run(
        [str(python), "-m", "pip", "--disable-pip-version-check", *args],
        check=True,
        text=True,
        capture_output=capture,
    )


def declared_dependencies() -> list[str]:
    with open(ROOT / "pyproject.toml", "rb") as f:
        pyproject = tomllib.load(f)
    project = pyproject["project"].get("dependencies", [])
    build = pyproject["build-system"].get("requires", [])
    return project + build


def lock() -> None:
    python = create_environment()
    pip(python, "install", *declared_dependencies())
    frozen = pip(python, "freeze", capture=True).stdout
    REQUIREMENTS.write_text(HEADER + frozen, newline="\n")


def rebuild() -> None:
    if not REQUIREMENTS.exists():
        sys.exit(
            f"{REQUIREMENTS.relative_to(ROOT)} is missing; "
            "run `cargo xtask python env lock` first."
        )
    python = create_environment()
    pip(python, "install", "-r", str(REQUIREMENTS))


@dataclass
class Step:
    label: str
    command: list[str]


def tool_environment() -> dict[str, str]:
    """The environment with ebi-pm first, if it exists."""
    environment = os.environ.copy()
    python = python_in(VENV)
    if not python.exists():
        sys.exit(
            "The ebi-pm environment is missing; "
            "run `cargo xtask python env rebuild` first."
        )
    environment["VIRTUAL_ENV"] = str(VENV)
    environment["PATH"] = str(python.parent) + os.pathsep + environment["PATH"]
    environment["PYO3_PYTHON"] = str(python)
    return environment


def summarise(log: str) -> tuple[str, list[str]]:
    ran = re.findall(r"^Ran (\d+) tests?", log, re.MULTILINE)
    if not ran:
        return "see log", []
    problems = re.search(r"^FAILED \((.+)\)$", log, re.MULTILINE)
    failed_tests = re.findall(r"^(?:FAIL|ERROR): (\S+)", log, re.MULTILINE)
    outcome = problems.group(1) if problems else "all passed"
    return f"{ran[-1]} Python tests, {outcome}", failed_tests


def run_step(step: Step, environment: dict[str, str]) -> bool:
    VAR.mkdir(exist_ok=True)
    log = VAR / f"test-{step.label}.log"
    executable = shutil.which(step.command[0], path=environment["PATH"])
    if executable is None:
        print(
            f"{step.label}: FAILED, {step.command[0]} is not on the PATH",
            flush=True,
        )
        return False
    print(f"{step.label}: running {' '.join(step.command)}", flush=True)
    started = time.monotonic()
    with open(log, "w", encoding="utf-8") as out:
        result = subprocess.run(
            [executable, *step.command[1:]],
            cwd=ROOT,
            env=environment,
            stdout=out,
            stderr=subprocess.STDOUT,
        )
    seconds = time.monotonic() - started
    outcome = "ok" if result.returncode == 0 else "FAILED"
    text = log.read_text(encoding="utf-8", errors="replace")
    summary, failed_tests = summarise(text)
    print(
        f"{step.label}: {outcome} after {seconds:.0f}s, {summary} "
        f"({log.relative_to(ROOT)})",
        flush=True,
    )
    for name in failed_tests:
        print(f"      FAILED {name}", flush=True)
    return result.returncode == 0


def test(environment: dict[str, str]) -> bool:
    build = Step("python-build", ["maturin", "develop"])
    tests = Step("python-tests", PYTHON_TESTS)
    return run_step(build, environment) and run_step(tests, environment)


def test_wheel(environment: dict[str, str], release: bool = False) -> bool:
    """Build a real wheel, install it into a fresh environment, and run the
    Python tests against that install."""
    kind = "wheel-release" if release else "wheel"
    wheels = VAR / f"{kind}s"
    wheel_environment = VAR / f"{kind}-env"
    shutil.rmtree(wheels, ignore_errors=True)
    build = [
        "maturin", "build", *(["--release"] if release else []),
        "--out", str(wheels),
    ]
    if not run_step(Step(f"{kind}-build", build), environment):
        return False
    wheel = next(wheels.glob("*.whl"))
    venv.EnvBuilder(clear=True, with_pip=True).create(wheel_environment)
    python = str(python_in(wheel_environment))
    pip_install = [
        python, "-m", "pip", "--disable-pip-version-check", "install",
    ]
    steps = [
        Step(f"{kind}-requirements", [*pip_install, "-r", str(REQUIREMENTS)]),
        Step(f"{kind}-install", [*pip_install, "--no-deps", str(wheel)]),
        Step(f"{kind}-tests", [python, *PYTHON_TESTS[1:]]),
    ]
    return all(run_step(step, environment) for step in steps)


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    commands = parser.add_subparsers(dest="command", required=True)
    env = commands.add_parser("env", help="manage the ebi-pm environment")
    env.add_argument("action", choices=["lock", "rebuild"])
    commands.add_parser("test", help="maturin develop, then the Python tests")
    commands.add_parser("wheel", help="test an installed debug wheel")
    commands.add_parser("wheel-release", help="test an installed release wheel")
    args = parser.parse_args()
    if args.command == "env":
        {"lock": lock, "rebuild": rebuild}[args.action]()
        return
    environment = tool_environment()
    if args.command == "test":
        ok = test(environment)
    else:
        ok = test_wheel(environment, release=args.command == "wheel-release")
    if not ok:
        sys.exit(1)


if __name__ == "__main__":
    main()
